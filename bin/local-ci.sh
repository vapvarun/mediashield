#!/usr/bin/env bash
# bin/local-ci.sh — local-CI gate for MediaShield.
#
# Single entry point that runs every quality + correctness + journey
# check in the right order. Designed to be runnable from a fresh clone
# without GitHub Actions or any external infrastructure.
#
# Usage:
#   composer ci                         # via composer script
#   bash bin/local-ci.sh                # direct, all stages
#   bash bin/local-ci.sh --no-journeys  # skip browser-dependent stages
#   bash bin/local-ci.sh --quick        # lint + coding-rules only (~10s)
#
# Exit 0 = green; non-zero = at least one stage failed (the offending
# stage's stdout/stderr was already printed). Each stage has a numeric
# tag (1.x = static, 2.x = security, 3.x = manifest, 4.x = journeys)
# so you can scroll back to the first red.
#
# Generated by wp-plugin-onboard skill. Edit freely — this is your
# plugin's CI orchestrator, not skill state.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLUGIN_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
PLUGIN_SLUG="$(basename "$PLUGIN_DIR")"

cd "$PLUGIN_DIR"

MODE="full"
# Site URL comes from docs/qa/qa-config.json when present, so this script and
# /wp-plugin-smoke cannot disagree about which site to test. They did: this
# defaulted to mediashield.local while qa-config said lms.local, so the journeys
# stage had never once run - it reported "site not reachable" and was counted as
# a warning.
QA_CONFIG_URL=""
if [ -f docs/qa/qa-config.json ] && command -v jq >/dev/null 2>&1; then
  QA_CONFIG_URL="$(jq -r '.base_url // empty' docs/qa/qa-config.json 2>/dev/null)"
fi
SITE_URL="${LOCAL_CI_SITE_URL:-${QA_CONFIG_URL:-http://mediashield.local}}"

while [ $# -gt 0 ]; do
  case "$1" in
    --no-journeys) MODE="no-journeys" ;;
    --quick)       MODE="quick" ;;
    --site)        SITE_URL="$2"; shift ;;
    *) echo "Unknown flag: $1"; exit 2 ;;
  esac
  shift
done

# ─── helpers ─────────────────────────────────────────────────────────────────

FAILED=()
# A gate that did not run proves nothing, so skips are tracked and the run ends
# non-zero. Ported from Pro (BC#10235757874); free was never swept.
SKIPPED=()
GREEN="\033[0;32m"; RED="\033[0;31m"; YELLOW="\033[0;33m"; DIM="\033[2m"; RESET="\033[0m"

step() { printf "${DIM}[%s]${RESET} %s\n" "$1" "${@:2}"; }
pass() { printf "${GREEN}✓${RESET}  %s\n" "$*"; }
fail() { printf "${RED}✗${RESET}  %s\n" "$*"; FAILED+=("$1"); }
warn() { printf "${YELLOW}!${RESET}  %s\n" "$*"; }

run_stage() {
  local tag="$1"; local label="$2"; shift 2
  step "$tag" "$label"
  if "$@" > /tmp/local-ci-$$.log 2>&1; then
    pass "$label"
  else
    fail "$tag $label"
    cat /tmp/local-ci-$$.log | sed 's/^/    /'
  fi
  rm -f /tmp/local-ci-$$.log
}

echo "=== MediaShield local-CI ==="
echo "Mode: $MODE  ·  Site: $SITE_URL"
echo ""

# ─── 1.x — Static checks (fast, no runtime needed) ───────────────────────────

# 1.0 runs FIRST and on its own: a committed autoloader that references
# uncommitted paths fatals on `require vendor/autoload.php`, so every stage
# after this one would fail for a reason that has nothing to do with the code
# being tested. Cheap, and it is the only gate that catches a break which is
# invisible in an existing checkout.
step "1.0" "Committed-autoloader integrity"
if php bin/check-vendor-autoload.php; then
  pass "Committed autoloader matches committed vendor tree"
else
  fail "1.0 Committed-autoloader integrity"
fi

step "1.1" "PHP lint (every changed-source PHP file)"
PHP_LINT_FAILED=0
while IFS= read -r -d '' file; do
  if ! php -l "$file" > /dev/null 2>&1; then
    fail "1.1 PHP lint: $file"
    php -l "$file" 2>&1 | sed 's/^/    /'
    PHP_LINT_FAILED=1
  fi
done < <(find . -type f -name '*.php' \
          -not -path './vendor/*' \
          -not -path './node_modules/*' \
          -not -path './tests/*' \
          -not -path './build/*' \
          -not -path './dist/*' \
          -not -path './.git/*' \
          -print0)
[ "$PHP_LINT_FAILED" = "0" ] && pass "PHP lint clean"

# ─── Dev autoloader, temporarily ─────────────────────────────────────────────
#
# The COMMITTED autoloader must be --no-dev: it ships to customers, and one
# built with dev requirements took every site down on a fresh clone. But phpcs,
# phpstan and phpunit are all dev requirements, so with the shipped autoloader
# none of them can load - which is why 1.3 PHPStan failed on a clean checkout
# and stayed red. Build a dev autoloader for the run, put the shipped one back
# afterwards. The trap covers a failing gate and a Ctrl-C alike, because a tree
# left holding a dev autoloader is the state that caused the outage.
RESTORE_AUTOLOAD=0
restore_autoload() {
  if [ "$RESTORE_AUTOLOAD" = "1" ]; then
    composer dump-autoload --no-dev --quiet 2>/dev/null || true
    RESTORE_AUTOLOAD=0
  fi
}
trap restore_autoload EXIT INT TERM

if [ "$MODE" != "quick" ] && [ -d vendor/phpunit ] && ! grep -q "phpunit" vendor/composer/autoload_classmap.php 2>/dev/null; then
  composer dump-autoload --quiet 2>/dev/null && RESTORE_AUTOLOAD=1
fi

if [ "$MODE" = "quick" ]; then
  step "QUICK" "skipping WPCS / PHPStan / wppqa / journeys"
else
  if [ -f phpcs.xml ] || [ -f .phpcs.xml.dist ]; then
    if [ -x vendor/bin/phpcs ]; then
      run_stage "1.2" "WPCS (phpcs)" composer phpcs
    else
      warn "1.2 WPCS skipped — run 'composer install' first"
      SKIPPED+=("1.2 WPCS")
    fi
  fi

  if [ -f phpstan.neon ] || [ -f phpstan.neon.dist ]; then
    if [ -x vendor/bin/phpstan ]; then
      run_stage "1.3" "PHPStan static analysis" composer phpstan
    else
      warn "1.3 PHPStan skipped — vendor/bin/phpstan not present"
      SKIPPED+=("1.3 PHPStan")
    fi
  fi

  # The suite itself. There was no PHPUnit stage here at all, so the 58 tests in
  # tests/unit/ were run by nothing - every "tests pass" claim on Free was a
  # statement about a command someone ran by hand, if at all.
  if [ -f phpunit.xml ] || [ -f phpunit.xml.dist ]; then
    if [ -x vendor/bin/phpunit ]; then
      run_stage "1.4" "PHPUnit test suite" vendor/bin/phpunit
    else
      warn "1.4 PHPUnit skipped — vendor/bin/phpunit not present"
      SKIPPED+=("1.4 PHPUnit")
    fi
  fi
fi

# ─── 2.x — Security + Architecture (always cheap) ────────────────────────────

if [ -x bin/coding-rules-check.sh ]; then
  run_stage "2.1" "Coding-rules check" bash bin/coding-rules-check.sh
fi

if [ -x bin/architecture-checks.sh ]; then
  run_stage "2.2" "Architecture invariants (plan/INVARIANTS.yaml gates)" bash bin/architecture-checks.sh
fi

# ─── 3.x — Manifest freshness ────────────────────────────────────────────────

if [ "$MODE" != "quick" ]; then
  if [ -f audit/manifest.json ]; then
    if jq . audit/manifest.json > /dev/null 2>&1; then
      pass "3.1 Manifest is valid JSON"

      MANIFEST_AT="$(jq -r '.generated.at // empty' audit/manifest.json)"
      if [ -n "$MANIFEST_AT" ]; then
        AGE_DAYS=$(( ($(date -u +%s) - $(date -juf "%Y-%m-%dT%H:%M:%SZ" "$MANIFEST_AT" +%s 2>/dev/null || echo 0)) / 86400 ))
        if [ "$AGE_DAYS" -gt 30 ]; then
          warn "3.1 Manifest is ${AGE_DAYS}d old — refresh via /wp-plugin-onboard --refresh"
        fi
      fi
    else
      fail "3.1 Manifest JSON invalid"
    fi
  else
    warn "3.1 No audit/manifest.json — run /wp-plugin-onboard"
  fi
fi

# ─── 4.x — Journeys (browser-dependent, can be skipped) ──────────────────────

if [ "$MODE" = "full" ]; then
  if [ -d audit/journeys ] && [ -x bin/run-journeys.sh ]; then
    if curl -fsS "$SITE_URL" > /dev/null 2>&1; then
      run_stage "4.1" "Customer journeys (browser+REST+DB)" bash bin/run-journeys.sh --site "$SITE_URL"
    else
      warn "4.1 Journeys skipped — site $SITE_URL is not reachable"
      SKIPPED+=("4.1 Journeys")
    fi
  fi
fi

# ─── 5.x — Scale benchmark (mandatory for production-readiness gate) ────────
# Runs `wp <slug> scale benchmark` if the ScaleCommand is registered.
# Caller is expected to have seeded test data via `wp <slug> scale seed`
# beforehand on a dev box; in CI, seed inline before benchmark and teardown
# after. Skipped silently when the command isn't registered yet (new
# plugins still scaffolding their hot-path budgets).

if [ "$MODE" = "full" ] && command -v wp > /dev/null 2>&1; then
  PLUGIN_SLUG="${PLUGIN_SLUG:-mediashield}"
  if wp "$PLUGIN_SLUG" scale --help > /dev/null 2>&1; then
    run_stage "5.1" "Scale benchmark (hot-path query budgets)" wp "$PLUGIN_SLUG" scale benchmark
  fi
fi

# ─── Summary ─────────────────────────────────────────────────────────────────

echo ""
echo "=== Summary ==="
if [ ${#FAILED[@]} -eq 0 ] && [ ${#SKIPPED[@]} -eq 0 ]; then
  printf "${GREEN}local-CI green${RESET}\n"
  exit 0
elif [ ${#FAILED[@]} -eq 0 ]; then
  printf "${YELLOW}local-CI incomplete: %d gate(s) could not run${RESET}\n" "${#SKIPPED[@]}"
  for stage in "${SKIPPED[@]}"; do
    printf "  ${YELLOW}!${RESET} %s\n" "$stage"
  done
  printf "\nNothing failed, but this is not a pass - a gate that did not run\n"
  printf "proves nothing. Make the listed gates runnable and re-run.\n"
  exit 1
else
  printf "${RED}local-CI failed: %d stage(s)${RESET}\n" "${#FAILED[@]}"
  for stage in "${FAILED[@]}"; do
    printf "  ${RED}✗${RESET} %s\n" "$stage"
  done
  exit 1
fi
